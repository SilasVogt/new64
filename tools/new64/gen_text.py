#!/usr/bin/env python3
"""Generate text/us/new64_courses.inc.c: SM64-encoded name and act strings for
the new courses, written into the arrays that text/us/courses.h declares.

Vanilla names come from the ROM at runtime; ours aren't in the ROM, so a
constructor fills the (otherwise 0xFF) placeholder arrays before the text
tables are first read. Prints the COURSE_ACTS lines for courses.h.

Usage: gen_text.py <repo root>
"""
import re
import sys
from pathlib import Path

COURSES = [
    ("COURSE_SGI", "16 SKY GARDEN ISLES", [
        "KING BOB-OMB'S SKY ARENA",
        "TOP OF THE CLOUD TOWER",
        "RED COINS ON THE ISLES",
        "BLAST TO THE LONELY ISLE",
        "FIVE SECRETS IN THE SKY",
        "THE BOX ABOVE THE BRIDGE",
    ]),
    ("COURSE_FFJ", "17 FROSTFIRE FJORD", [
        "THE BIG CHILL IN THE MAGMA HALL",
        "GEYSER RIDE TO THE BASALT SPIRE",
        "RED COINS IN THE GLACIER CAVE",
        "LUNDI PATROL ON THE SEA STACKS",
        "BEHIND THE ROARING WATERFALL",
        "STEPPING STONES IN THE CRATER",
    ]),
]


def load_charmap(root):
    cmap = {}
    for line in (root / "charmap.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^'(\\'|.)' = (0x[0-9A-Fa-f]+)\s*$", line)
        if m:
            ch = "'" if m.group(1) == "\\'" else m.group(1)
            cmap.setdefault(ch, int(m.group(2), 16))
    return cmap


def encode(cmap, text):
    return [cmap[c] for c in text] + [0xFF]


def main():
    root = Path(sys.argv[1])
    cmap = load_charmap(root)
    out = ["// Generated by tools/new64/gen_text.py. Do not edit.", ""]
    all_entries = []
    for course, name, acts in COURSES:
        entries = [(f"seg2_course_name_table_{course}", encode(cmap, name))]
        entries += [(f"act_name_{course}_{i + 1}", encode(cmap, a)) for i, a in enumerate(acts)]
        all_entries += entries
        lens = [len(d) for _, d in entries]
        print(f"COURSE_ACTS({course}, {', '.join(map(str, lens))})")
    for name, data in all_entries:
        out.append(f"static const u8 new64_{name}[] = {{ {', '.join(f'0x{b:02X}' for b in data)} }};")
    out += ["", "__attribute__((constructor)) static void new64_course_text_init(void) {"]
    for name, data in all_entries:
        out.append(f"    _Static_assert(sizeof({name}) == sizeof(new64_{name}), \"courses.h length mismatch\");")
        out.append(f"    for (unsigned i = 0; i < sizeof(new64_{name}); i++) {{ {name}[i] = new64_{name}[i]; }}")
    out += ["}", ""]
    (root / "text/us/new64_courses.inc.c").write_text("\n".join(out))


if __name__ == "__main__":
    main()
